"""Fleet provisioning — herdr roster for the whole BOND suite.

bond-ops is the QUARTERMASTER: it renders the herdr provisioning commands that
stand up one herdr workspace (auto-creating a tab + root shell pane) and one
Hermes agent per package, following the suite's herdr provisioning procedure
(``herdr-multiple-hermes-dispatch`` skill + ``SCOPE.md`` runtime notes):

    1. ``herdr workspace create --label <slug> --cwd <suite>/<slug> --no-focus``
       (returns a JSON payload whose ``root_pane.pane_id`` is captured)
    2. ``herdr agent start <slug> --kind hermes --pane <pane> --timeout 90000``
    3. ``herdr agent prompt <slug> "$(cat <prompt>)"``  (fire-and-forget brief;
       emitted only when a prompt file for the package exists)

These are *informational by default* — rendering is pure and deterministic, and
nothing is executed unless ``--execute`` is given (the default path stays
read-only and safe). When executed, every ``herdr`` invocation is a real
subprocess via ``bash``; the binary is resolved through ``PATH`` so a test can
substitute a fake ``herdr`` without mocks.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from .gates import CommandResult, run_command
from .inventory import DEFAULT_SUITE_ROOT, ROSTER, PackageRecord

#: Informational header prepended to the printed roster (read-only default).
PROVISION_HEADER = (
    "# PROJECT BOND fleet provisioning (informational — nothing runs without --execute)"
)

#: Default herdr executable name (resolved through PATH at execution time).
HEDR_BIN = "herdr"

#: Default ``agent start`` interactivity wait (milliseconds), per the skill.
AGENT_START_TIMEOUT_MS = 90000


@dataclass(frozen=True)
class RosterEntry:
    """One package's provisioning identity."""

    slug: str
    kind: str  # "film" | "infra"
    codename: str
    cwd: str  # absolute path under the suite root
    prompt: str | None = None  # mission prompt file path, if one exists


def _first_existing(paths: list[Path]) -> str | None:
    for path in paths:
        if path.is_file():
            return str(path)
    return None


def resolve_prompt(root_prompt_dir: str | Path, slug: str, kind: str) -> str | None:
    """Locate a mission prompt file for ``slug`` under ``root_prompt_dir``.

    Infrastructure packages keep prompts under ``<prompts>/infra/<slug>.txt``;
    film packages under ``<prompts>/<slug>.txt``. Returns ``None`` when no
    prompt file exists for the package (the brief step is then omitted).
    """
    root = Path(root_prompt_dir)
    candidates: list[Path] = []
    if kind == "infra":
        candidates += [
            root / "infra" / f"{slug}.txt",
            root / "infra" / f"{slug}.md",
        ]
    candidates += [
        root / f"{slug}.txt",
        root / f"{slug}.md",
    ]
    return _first_existing(candidates)


def build_roster(
    roster_: tuple[PackageRecord, ...] = ROSTER,
    suite_root: str | Path | None = None,
    prompt_dir: str | Path | None = None,
) -> tuple[RosterEntry, ...]:
    """Build the deterministic provisioning roster for the fleet.

    One :class:`RosterEntry` per package, in canonical roster order (infra
    first, then films by rank). ``cwd`` is always the package's directory under
    ``suite_root``; ``prompt`` is resolved against ``prompt_dir`` when given.
    """
    root = Path(suite_root) if suite_root is not None else DEFAULT_SUITE_ROOT
    entries: list[RosterEntry] = []
    for rec in roster_:
        prompt: str | None = None
        if prompt_dir is not None:
            prompt = resolve_prompt(prompt_dir, rec.slug, rec.kind)
        entries.append(
            RosterEntry(
                slug=rec.slug,
                kind=rec.kind,
                codename=rec.codename,
                cwd=str(root / rec.slug),
                prompt=prompt,
            )
        )
    return tuple(entries)


def render_provision_script(
    entries: tuple[RosterEntry, ...],
    *,
    herdr: str = HEDR_BIN,
    agent_timeout: int = AGENT_START_TIMEOUT_MS,
) -> str:
    """Render a deterministic, shell-runnable provisioning script.

    The script first confirms the herdr daemon is reachable, then for every
    package creates a workspace, starts a Hermes agent in its pane, and (when a
    mission prompt file exists) submits that brief fire-and-forget.
    """
    lines: list[str] = [
        "#!/usr/bin/env bash",
        "# PROJECT BOND fleet provisioning — generated by bond-ops (QUARTERMASTER).",
        "# Informational roster; run `ops roster --execute` to actually execute.",
        "set -euo pipefail",
        "",
        "# 0. Confirm the herdr daemon is reachable; abort early if not.",
        f"{herdr} status >/dev/null 2>&1 || {{ echo 'ERROR: herdr daemon not running (start: herdr server)' >&2; exit 1; }}",
        "",
    ]
    for entry in entries:
        lines.append(f"# {entry.slug} ({entry.kind}) — cwd {entry.cwd}")
        lines.append(
            f'out=$({herdr} workspace create --label {entry.slug} --cwd "{entry.cwd}" --no-focus)'
        )
        lines.append(
            "pane=$(printf '%s' \"$out\" | python3 -c "
            "\"import sys,json;print(json.load(sys.stdin)['result']['root_pane']['pane_id'])\")"
        )
        lines.append(
            f'{herdr} agent start {entry.slug} --kind hermes --pane "$pane" --timeout {agent_timeout}'
        )
        if entry.prompt is not None:
            lines.append(f'{herdr} agent prompt {entry.slug} "$(cat "{entry.prompt}")"')
        else:
            lines.append(
                f"# (no mission prompt file for {entry.slug}; supply one under the "
                "prompts dir to brief this agent)"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def format_provision(
    roster_: tuple[PackageRecord, ...] = ROSTER,
    suite_root: str | Path | None = None,
    prompt_dir: str | Path | None = None,
) -> str:
    """Render the provisioning roster as read-only informational text."""
    entries = build_roster(roster_, suite_root, prompt_dir)
    return PROVISION_HEADER + "\n" + render_provision_script(entries)


def roster_report(entries: tuple[RosterEntry, ...]) -> dict[str, object]:
    """Deterministic, machine-readable provisioning roster report.

    Summarises the fleet by kind and prompt-brief coverage, then lists every
    entry (slug, kind, codename, cwd, prompt). No wall-clock; byte-identical
    for a given fleet state.
    """
    with_prompt = [e.slug for e in entries if e.prompt is not None]
    return {
        "manifest": "bond-ops-roster",
        "schema_version": 1,
        "summary": {
            "total": len(entries),
            "infra": sum(1 for e in entries if e.kind == "infra"),
            "film": sum(1 for e in entries if e.kind == "film"),
            "with_prompt": len(with_prompt),
            "without_prompt": len(entries) - len(with_prompt),
        },
        "entries": [
            {
                "slug": e.slug,
                "kind": e.kind,
                "codename": e.codename,
                "cwd": e.cwd,
                "prompt": e.prompt,
            }
            for e in entries
        ],
    }


def execute_script(script: str, *, timeout: int = 600) -> CommandResult:
    """Run a rendered provisioning script through the shell (real subprocess).

    Only call with ``--execute``. ``herdr`` is resolved through ``PATH``, so a
    test may prepend a fake ``herdr`` without mocks. ``set -euo pipefail``
    aborts on the first failed command.
    """
    return run_command(("bash", "-c", script), cwd=".", timeout=timeout)
